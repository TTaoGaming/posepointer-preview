/** Sample a stock M/L/C path at evenly spaced arc lengths. */
export function sampleStroke(path) {
  const tokens = path.match(/[MLC]|-?(?:\d*\.\d+|\d+\.?\d*)/g);
  const vertices = [];
  let length = 0;
  let current;
  let i = 0;

  function readPoint() {
    return { x: Number(tokens[i++]), y: Number(tokens[i++]) };
  }

  function append(point) {
    if (current) length += Math.hypot(point.x - current.x, point.y - current.y);
    vertices.push({ ...point, length });
    current = point;
  }

  while (i < tokens.length) {
    const command = tokens[i++];
    if (command === 'M' || command === 'L') {
      append(readPoint());
    } else if (command === 'C') {
      const start = current;
      const a = readPoint();
      const b = readPoint();
      const end = readPoint();
      for (let step = 1; step <= 200; step++) {
        const t = step / 200;
        const u = 1 - t;
        const c0 = u * u * u;
        const c1 = 3 * u * u * t;
        const c2 = 3 * u * t * t;
        const c3 = t * t * t;
        append({
          x: c0 * start.x + c1 * a.x + c2 * b.x + c3 * end.x,
          y: c0 * start.y + c1 * a.y + c2 * b.y + c3 * end.y
        });
      }
    }
  }

  const count = Math.max(2, Math.ceil(length / 2));
  let segment = 1;
  return Array.from({ length: count + 1 }, (_, index) => {
    if (index === 0) return { x: vertices[0].x, y: vertices[0].y };
    if (index === count || length === 0) return { x: current.x, y: current.y };
    const target = length * index / count;
    while (vertices[segment].length < target) segment++;
    const from = vertices[segment - 1];
    const to = vertices[segment];
    const t = (target - from.length) / (to.length - from.length);
    return { x: from.x + (to.x - from.x) * t, y: from.y + (to.y - from.y) * t };
  });
}

const START_RADIUS = 22;

function distanceToSegment(point, from, to) {
  const dx = to.x - from.x;
  const dy = to.y - from.y;
  const squared = dx * dx + dy * dy;
  if (!squared) return Math.hypot(point.x - from.x, point.y - from.y);
  const fraction = ((point.x - from.x) * dx + (point.y - from.y) * dy) / squared;
  const t = Math.max(0, Math.min(1, fraction));
  return Math.hypot(point.x - (from.x + t * dx), point.y - (from.y + t * dy));
}

/** Origins optionally keep a held pointer's travel continuous across glyphs. */
export function createJudge({ strokes, origins }) {
  let pressed = false;
  let drawing = false;
  let stroke = 0;
  let prog = 0;
  let previous = null;

  function state() {
    return { pressed, drawing, stroke, prog, done: stroke === strokes.length };
  }

  function result(event) {
    return { event, stroke, prog };
  }

  function begin() {
    drawing = true;
    prog = 0;
    return result('begin');
  }

  function accept() {
    const accepted = result('accepted');
    stroke++;
    drawing = false;
    prog = 0;
    if (previous && origins && stroke < strokes.length) {
      const from = origins[stroke - 1];
      const to = origins[stroke];
      previous = { x: previous.x + from.x - to.x, y: previous.y + from.y - to.y };
    }
    return accepted;
  }

  function down(x, y) {
    pressed = true;
    previous = { x, y };
    const start = strokes[stroke]?.[0];
    if (start && Math.hypot(start.x - x, start.y - y) <= START_RADIUS) return begin();
    return result('none');
  }

  function move(x, y) {
    const points = strokes[stroke];
    if (!pressed || !points) return result('none');

    const from = previous;
    previous = { x, y };
    if (!drawing) {
      const start = points[0];
      if (Math.hypot(start.x - x, start.y - y) <= START_RADIUS ||
          distanceToSegment(start, from, previous) <= START_RADIUS) return begin();
      return result('none');
    }

    const first = Math.max(0, Math.floor(prog) - 3);
    const last = Math.min(points.length - 1, Math.floor(prog) + 46);
    let best = -1;
    let distance = Infinity;
    for (let i = first; i <= last; i++) {
      const d = Math.hypot(points[i].x - x, points[i].y - y);
      if (d < distance) {
        best = i;
        distance = d;
      }
    }

    if (distance <= 13 && best > prog + 0.4) {
      prog = best;
      if (prog >= points.length - 4) return accept();
      return result('progress');
    }
    return result('none');
  }

  function up() {
    pressed = false;
    previous = null;
    if (!drawing) return result('none');

    const count = strokes[stroke].length;
    if (prog >= count - 6 || prog >= 0.94 * count) return accept();

    drawing = false;
    prog = 0;
    return result('retry');
  }

  return { down, move, up, cancel: up, state };
}

export function judgeRun({ text, events }) {
  const strokes = Array.from(text).flatMap(ch => (GLYPHS[ch]?.s ?? []).map(sampleStroke));
  const judge = createJudge({ strokes });
  const attempts = [];
  let active;

  for (const { type, x, y } of events) {
    const result = judge[type](x, y);
    if (result.event === 'begin' && !active) {
      active = { stroke: result.stroke, outcome: 'open' };
      attempts.push(active);
    } else if (result.event === 'accepted' || result.event === 'retry') {
      active.outcome = result.event;
      active = undefined;
    }
  }

  const state = judge.state();
  return { complete: state.done, accepted: state.stroke, attempts, state };
}
